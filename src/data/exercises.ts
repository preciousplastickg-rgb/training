export const EXERCISES: Exercise[] = [...EXERCISES_V1, ...EXERCISES_V2];

export const EXERCISE_BY_ID: Record<string, Exercise> = Object.fromEntries(EXERCISES.map((e) => [e.id, e]));

export function getExercise(id: string): Exercise {
  const ex = EXERCISE_BY_ID[id];
  if (!ex) throw new Error(`Неизвестное упражнение: ${id}`);
  return ex;
}

/** Ссылка на поиск видео (нужна сеть). */
export function videoUrl(ex: Exercise): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(ex.videoQuery)}`;
}
